#!/usr/bin/env python3
"""Unit tests for the hardlink-clone node_modules bootstrap (stdlib unittest).

Exercises real throwaway git checkouts for the branch-derived spec id (the
logic under test *is* the git plumbing), and real sibling directories on disk
for the hardlink-clone / fallback decision tree -- a fake filesystem would
just re-assert the mock.
"""

from __future__ import annotations

import subprocess
import tempfile
import unittest
from pathlib import Path

from worktrail.orchestrator import bootstrap_node_modules as bnm


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", *args], cwd=str(repo), capture_output=True, text=True, check=True
    )


def _init_repo_at(path: Path, branch: str) -> Path:
    """Create a real git checkout at `path` on `branch`, with one commit so
    `HEAD` is resolvable (a freshly `git worktree add`-ed task worktree always
    starts from an existing commit; an unborn-HEAD repo is not representative)."""
    path.mkdir(parents=True, exist_ok=True)
    _git(path, "init", "-q", "-b", branch)
    _git(path, "config", "user.email", "test@example.com")
    _git(path, "config", "user.name", "Test")
    (path / "README.md").write_text("base\n", encoding="utf-8")
    _git(path, "add", ".")
    _git(path, "commit", "-q", "-m", "base")
    return path


class CurrentSpecIdTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)

    def test_splits_spec_id_off_task_branch(self):
        wt = _init_repo_at(Path(self._tmp.name) / "wt", "025-feature/task-001")
        self.assertEqual(bnm.current_spec_id(wt), "025-feature")

    def test_branch_with_no_slash_is_not_a_task_branch(self):
        wt = _init_repo_at(Path(self._tmp.name) / "wt", "main")
        self.assertIsNone(bnm.current_spec_id(wt))

    def test_non_git_dir_returns_none(self):
        empty = Path(self._tmp.name) / "not-a-repo"
        empty.mkdir()
        self.assertIsNone(bnm.current_spec_id(empty))


class SiblingSpecWorktreeTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.base = Path(self._tmp.name)

    def test_finds_sibling_by_naming_convention(self):
        spec_wt = self.base / "025-feature-spec"
        spec_wt.mkdir()
        task_wt = _init_repo_at(
            self.base / "025-feature-task-001", "025-feature/task-001"
        )
        self.assertEqual(bnm.sibling_spec_worktree(task_wt), spec_wt)

    def test_missing_sibling_is_none(self):
        task_wt = _init_repo_at(
            self.base / "025-feature-task-001", "025-feature/task-001"
        )
        self.assertIsNone(bnm.sibling_spec_worktree(task_wt))


class LockfileMatchesTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.spec_dir = Path(self._tmp.name) / "spec"
        self.task_dir = Path(self._tmp.name) / "task"
        self.spec_dir.mkdir()
        self.task_dir.mkdir()

    def test_identical_lockfiles_match(self):
        (self.spec_dir / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")
        (self.task_dir / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")
        self.assertTrue(
            bnm.lockfile_matches(self.spec_dir, self.task_dir, "package-lock.json")
        )

    def test_different_lockfiles_do_not_match(self):
        (self.spec_dir / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")
        (self.task_dir / "package-lock.json").write_text('{"a":2}\n', encoding="utf-8")
        self.assertFalse(
            bnm.lockfile_matches(self.spec_dir, self.task_dir, "package-lock.json")
        )

    def test_missing_lockfile_does_not_match(self):
        (self.spec_dir / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")
        self.assertFalse(
            bnm.lockfile_matches(self.spec_dir, self.task_dir, "package-lock.json")
        )


class HardlinkCloneTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.src = Path(self._tmp.name) / "node_modules"
        self.src.mkdir()
        (self.src / "leftpad").mkdir()
        (self.src / "leftpad" / "index.js").write_text(
            "module.exports = {};\n", encoding="utf-8"
        )

    def test_clone_hardlinks_files(self):
        dest = Path(self._tmp.name) / "dest"
        self.assertTrue(bnm.hardlink_clone(self.src, dest))
        cloned = dest / "leftpad" / "index.js"
        self.assertTrue(cloned.exists())
        self.assertEqual(cloned.read_text(), "module.exports = {};\n")
        # Real hardlink, not a content copy: same inode as the source file.
        self.assertEqual(
            cloned.stat().st_ino, (self.src / "leftpad" / "index.js").stat().st_ino
        )

    def test_refuses_to_clobber_existing_dest(self):
        dest = Path(self._tmp.name) / "dest"
        dest.mkdir()
        self.assertFalse(bnm.hardlink_clone(self.src, dest))


class BootstrapIntegrationTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.base = Path(self._tmp.name)

    def _task_wt(self, spec_id: str = "025-feature", task_id: str = "task-001") -> Path:
        return _init_repo_at(self.base / f"{spec_id}-{task_id}", f"{spec_id}/{task_id}")

    def test_no_sibling_falls_back_to_install(self):
        task_wt = self._task_wt()
        result = bnm.bootstrap(task_wt, app_dir=".", install_cmd="touch INSTALLED")
        self.assertEqual(result["method"], "install")
        self.assertTrue(result["ok"])
        self.assertTrue((task_wt / "INSTALLED").exists())

    def test_sibling_without_node_modules_falls_back(self):
        (self.base / "025-feature-spec").mkdir()
        task_wt = self._task_wt()
        result = bnm.bootstrap(task_wt, app_dir=".", install_cmd="touch INSTALLED")
        self.assertEqual(result["method"], "install")
        self.assertIn("no node_modules", result["reason"])

    def test_matching_lockfile_hardlink_clones(self):
        spec_wt = self.base / "025-feature-spec"
        spec_wt.mkdir()
        (spec_wt / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")
        (spec_wt / "node_modules").mkdir()
        (spec_wt / "node_modules" / "pkg.js").write_text("x\n", encoding="utf-8")

        task_wt = self._task_wt()
        (task_wt / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")

        result = bnm.bootstrap(task_wt, app_dir=".", install_cmd="touch INSTALLED")
        self.assertEqual(result["method"], "hardlink")
        self.assertTrue(result["ok"])
        self.assertTrue((task_wt / "node_modules" / "pkg.js").exists())
        self.assertFalse((task_wt / "INSTALLED").exists())

    def test_mismatched_lockfile_falls_back_to_install(self):
        spec_wt = self.base / "025-feature-spec"
        spec_wt.mkdir()
        (spec_wt / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")
        (spec_wt / "node_modules").mkdir()

        task_wt = self._task_wt()
        (task_wt / "package-lock.json").write_text('{"a":2}\n', encoding="utf-8")

        result = bnm.bootstrap(task_wt, app_dir=".", install_cmd="touch INSTALLED")
        self.assertEqual(result["method"], "install")
        self.assertTrue((task_wt / "INSTALLED").exists())

    def test_failed_install_reports_not_ok(self):
        task_wt = self._task_wt()
        result = bnm.bootstrap(task_wt, app_dir=".", install_cmd="exit 7")
        self.assertEqual(result["method"], "install")
        self.assertFalse(result["ok"])

    def test_app_dir_is_respected(self):
        spec_wt = self.base / "025-feature-spec"
        spec_app = spec_wt / "app"
        spec_app.mkdir(parents=True)
        (spec_app / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")
        (spec_app / "node_modules").mkdir()
        (spec_app / "node_modules" / "pkg.js").write_text("x\n", encoding="utf-8")

        task_wt = self._task_wt()
        task_app = task_wt / "app"
        task_app.mkdir()
        (task_app / "package-lock.json").write_text('{"a":1}\n', encoding="utf-8")

        result = bnm.bootstrap(task_wt, app_dir="app", install_cmd="touch INSTALLED")
        self.assertEqual(result["method"], "hardlink")
        self.assertTrue((task_app / "node_modules" / "pkg.js").exists())


if __name__ == "__main__":
    unittest.main()
