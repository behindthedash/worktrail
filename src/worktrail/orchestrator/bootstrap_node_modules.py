#!/usr/bin/env python3
"""
Hardlink-clone `node_modules` bootstrap for per-task orchestrator worktrees.

`live.py`'s `bootstrap_worktree()` runs a repo's `worktree_bootstrap_cmd`
(worktrail-go-policy.yaml) once per freshly-created task worktree, outside the shared
`git_lock` so a slow install never serializes other tasks' worktree creation
-- but a full `npm ci` per task worktree is still real, serialized-against-one-
disk wall clock: 13 task worktrees fanned out from one spec each paying
~2-3min for an install that is byte-for-byte identical to the spec worktree's
own already-bootstrapped `node_modules` (observed: datalena spec 097).

`worktree.py`'s sibling-directory convention makes that redundancy avoidable
without any change to the orchestrator's own bootstrap contract: a spec
worktree and every task worktree fanned out from it live as siblings under
the same `<repo>-worktrees/` base (`<spec_id>-spec` and `<spec_id>-<task_id>`),
and a task worktree's own branch (`<spec_id>/<task_id>`) makes `<spec_id>`
derivable with nothing but `git rev-parse --abbrev-ref HEAD`. That means the
already-installed `node_modules` next door is always at a predictable path.

This module is a drop-in `worktree_bootstrap_cmd` value
(`worktrail-bootstrap-node-modules`, or `... --app-dir app` when package.json
isn't at the worktree root): it hardlink-clones (`cp -al`) the sibling spec
worktree's `node_modules` when its lockfile matches byte-for-byte, and falls
back to running the normal install command otherwise (no sibling worktree, no
`node_modules` there yet, or a lockfile mismatch -- e.g. a task branch that
edited the lockfile). `cp -al` hardlinks every file instead of copying
content, so the clone is near-instant and safe: neither copy's directory
entries share mutable state, and neither `npm`/`node` mutates files under
`node_modules` in place during normal use.
"""
from __future__ import annotations

import argparse
import filecmp
import json
import subprocess
import sys
from pathlib import Path
from typing import Dict, Optional


def _run(args, cwd: Optional[Path] = None, timeout: Optional[int] = None):
    """`args` as a list runs directly; a str runs via the shell (matches
    `worktree_bootstrap_cmd`'s own `subprocess.run(cmd, shell=True, ...)` contract)."""
    try:
        return subprocess.run(
            args, shell=isinstance(args, str), cwd=str(cwd) if cwd else None,
            capture_output=True, text=True, timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None


def current_spec_id(task_worktree: Path) -> Optional[str]:
    """The spec id a task worktree's own branch was fanned out from.

    Task branches follow `worktree.py`'s `task_branch()` convention:
    `<spec_id>/<task_id>`. `None` on a detached HEAD, an unresolvable repo, or
    a branch with no `/` (not a fan-out task branch).
    """
    out = _run(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=task_worktree, timeout=5)
    if out is None or out.returncode != 0:
        return None
    branch = out.stdout.strip()
    if "/" not in branch:
        return None
    return branch.split("/", 1)[0]


def sibling_spec_worktree(task_worktree: Path) -> Optional[Path]:
    """The spec worktree this task worktree was fanned out from, if present on disk.

    Sibling-directory layout (`worktree.py`): both live directly under the same
    `<repo>-worktrees/` base, named `<spec_id>-spec` and `<spec_id>-<task_id>`.
    """
    spec_id = current_spec_id(task_worktree)
    if not spec_id:
        return None
    candidate = task_worktree.parent / f"{spec_id}-spec"
    return candidate if candidate.is_dir() else None


def lockfile_matches(spec_app_dir: Path, task_app_dir: Path, lockfile: str) -> bool:
    """Byte-for-byte comparison of the two app dirs' lockfiles.

    False (never an error) when either lockfile is missing -- a missing
    lockfile is itself reason enough to fall back to a real install.
    """
    spec_lock = spec_app_dir / lockfile
    task_lock = task_app_dir / lockfile
    if not spec_lock.is_file() or not task_lock.is_file():
        return False
    try:
        return filecmp.cmp(spec_lock, task_lock, shallow=False)
    except OSError:
        return False


def hardlink_clone(src: Path, dest: Path) -> bool:
    """`cp -al src dest` -- a recursive hardlink clone. False on any failure."""
    if dest.exists():
        return False
    out = _run(["cp", "-al", str(src), str(dest)])
    return out is not None and out.returncode == 0


def run_install(app_dir: Path, install_cmd: str) -> bool:
    out = _run(install_cmd, cwd=app_dir)  # shell string; matches worktree_bootstrap_cmd's own contract
    return out is not None and out.returncode == 0


def bootstrap(
    task_worktree: Path,
    app_dir: str = ".",
    lockfile: str = "package-lock.json",
    install_cmd: str = "npm ci",
) -> Dict[str, object]:
    """Hardlink-clone from the sibling spec worktree, or fall back to `install_cmd`.

    Returns `{"method": "hardlink"|"install"|"failed", "reason": str, "ok": bool}`.
    """
    task_app_dir = task_worktree / app_dir
    spec_wt = sibling_spec_worktree(task_worktree)
    if spec_wt is None:
        ok = run_install(task_app_dir, install_cmd)
        return {"method": "install", "ok": ok, "reason": "no sibling spec worktree found"}

    spec_app_dir = spec_wt / app_dir
    spec_node_modules = spec_app_dir / "node_modules"
    if not spec_node_modules.is_dir():
        ok = run_install(task_app_dir, install_cmd)
        return {"method": "install", "ok": ok, "reason": "spec worktree has no node_modules yet"}

    if not lockfile_matches(spec_app_dir, task_app_dir, lockfile):
        ok = run_install(task_app_dir, install_cmd)
        return {"method": "install", "ok": ok, "reason": f"{lockfile} differs from spec worktree"}

    task_node_modules = task_app_dir / "node_modules"
    if hardlink_clone(spec_node_modules, task_node_modules):
        return {"method": "hardlink", "ok": True, "reason": f"cloned from {spec_wt.name}"}

    # Hardlink clone failed (e.g. cross-device, dest already existed) -- fall back.
    ok = run_install(task_app_dir, install_cmd)
    return {"method": "install", "ok": ok, "reason": "hardlink clone failed; installed instead"}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--app-dir", default=".",
        help="subdirectory of the worktree root containing package.json (default: worktree root)",
    )
    p.add_argument("--lockfile", default="package-lock.json")
    p.add_argument(
        "--install-cmd", default="npm ci",
        help="fallback install command, run with the app dir as cwd (default: npm ci)",
    )
    p.add_argument(
        "--cwd", default=None,
        help="task worktree root (default: current directory -- matches how "
             "bootstrap_worktree() invokes worktree_bootstrap_cmd)",
    )
    p.add_argument("--json", action="store_true")
    args = p.parse_args(argv)

    task_worktree = Path(args.cwd) if args.cwd else Path.cwd()
    result = bootstrap(
        task_worktree, app_dir=args.app_dir, lockfile=args.lockfile,
        install_cmd=args.install_cmd,
    )
    if args.json:
        print(json.dumps(result))
    else:
        status = "ok" if result["ok"] else "FAILED"
        print(f"bootstrap-node-modules: {result['method']} ({status}) -- {result['reason']}")
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
